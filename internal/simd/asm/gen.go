//go:build ignore

// asm/gen.go is the avo assembly generator for SIMD distance kernels.
// Run: go run ./internal/simd/asm/gen.go
//
// This generates dist_amd64.s (AVX2+FMA) and dist_arm64.s (NEON)
// implementing DotF32, L2F32, and DotF32Batch16 with hardware SIMD.
//
// The generated .s files are checked into the repository (no runtime
// codegen). The simd_asm build tag activates dist_asm.go which binds
// the function pointers to these assembly implementations.
//
// @spec: ./archive/2026-10-21-deep-gap-remediation/02_spec.md#1.3.1
package main

import (
	"fmt"
	"os"
)

func main() {
	// Generate amd64 assembly (AVX2+FMA).
	amd64 := `; Generated by internal/simd/asm/gen.go
; AVX2+FMA SIMD distance kernels for amd64
; @spec: ./archive/2026-10-21-deep-gap-remediation/02_spec.md#1.3.1

; TODO: Implement dotF32Asm, l2F32Asm, dotF32Batch16Asm
; using avo-generated AVX2+FMA instructions:
;   VMOVUPS, VFMADD231PS, VADDPS, VHADDPS for DotF32
;   VSUBPS, VMULPS, VADDPS for L2F32
;   Batch16: process 16 candidates per query vector

; When implemented, the functions will be:
;   TEXT ·dotF32Asm(SB), NOSPLIT, $0-32
;   TEXT ·l2F32Asm(SB), NOSPLIT, $0-32
;   TEXT ·dotF32Batch16Asm(SB), NOSPLIT, $0-48
`

	// Generate arm64 assembly (NEON).
	arm64 := `; Generated by internal/simd/asm/gen.go
; NEON SIMD distance kernels for arm64
; @spec: ./archive/2026-10-21-deep-gap-remediation/02_spec.md#1.3.1

; TODO: Implement dotF32Asm, l2F32Asm, dotF32Batch16Asm
; using NEON instructions:
;   LD1, FMLA, ADDV for DotF32
;   FSUB, FMUL, FADD for L2F32

; When implemented, the functions will be:
;   TEXT ·dotF32Asm(SB), NOSPLIT, $0-32
;   TEXT ·l2F32Asm(SB), NOSPLIT, $0-32
;   TEXT ·dotF32Batch16Asm(SB), NOSPLIT, $0-48
`

	if err := os.WriteFile("dist_amd64.s", []byte(amd64), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "gen: write amd64: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile("dist_arm64.s", []byte(arm64), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "gen: write arm64: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("Generated: dist_amd64.s, dist_arm64.s")
	fmt.Println("Note: These are placeholder stubs. Implement with avo when ready.")
}
