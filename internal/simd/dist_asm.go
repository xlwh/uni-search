//go:build simd_asm

// Package simd dist_asm.go is the SIMD assembly kernel dispatch entry
// point. When the `simd_asm` build tag is active, this file's init()
// binds the function pointers to the best available assembly
// implementation based on runtime ISA detection (cpu.go).
//
// Three-level fallback (amd64):
//   1. AVX2+FMA  → 256-bit kernels (dotF32Asm, l2F32Asm, ...)
//   2. SSE2       → 128-bit fallback kernels
//   3. (neither)  → pure Go baseline (bound via a safety init)
//
// arm64:
//   1. NEON       → dotF32Neon, l2F32Neon, ...
//   2. (no NEON)  → pure Go baseline
//
// The .s files (dist_amd64.s / dist_arm64.s) are generated by:
//   go run ./internal/simd/asm/gen.go
//
// To build with SIMD assembly: go build -tags simd_asm ./...
// To build with Pure Go fallback (default): go build ./...
//
// @spec: ./active_specs/2026-10-22-vsag-algo-integration/02_spec.md#2.1.5
package simd

func init() {
	// On amd64: three-level fallback AVX2+FMA → SSE2 → pure Go.
	// On arm64: NEON → pure Go.
	// On other archs: pure Go (no SIMD detected).
	dispatchSIMD()
}
